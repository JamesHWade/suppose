    await page.locator('#expectation-answer').fill('These are plausible values at 150, with no probability level.');
    await pause(page);
    await page.locator('#expectation-preview').click();
    await page.locator('#expectation-preview_card').filter({hasText:'Range has no probability interpretation'}).waitFor();
    await page.locator('#expectation-retain').click();
    await page.locator('#expectation-retained').filter({hasText:'plausible values at 150'}).waitFor();
