"""Local OpenAI protocol fixture for streaming integration checks, not inference."""
from http.server import BaseHTTPRequestHandler, HTTPServer
import json

class Handler(BaseHTTPRequestHandler):
    def do_POST(self):
        request = json.loads(self.rfile.read(int(self.headers['Content-Length'])))
        messages = request['messages']
        user = next(m['content'] for m in reversed(messages) if m['role'] == 'user')
        if isinstance(user, list):
            user = '\n'.join(x.get('text', '') for x in user)
        tools = []
        # The fixture never interprets arbitrary text; this exact script is its test input.
        if messages[-1]['role'] != 'tool' and user == 'Fixture: higher strength, threshold 5 MPa.':
            tools = [dict(index=0, id='fixture_call', type='function', function=dict(
                name='propose_claim', arguments=json.dumps(dict(wording='Higher cure temperature increases mean batch strength',
                threshold=5, source_quote=user, reason='Local scripted integration fixture'))))]
        delta = {'role': 'assistant'}
        if tools:
            delta['tool_calls'] = tools
        else:
            delta['content'] = 'LOCAL FIXTURE: Review the scripted proposal. This response was not generated by Muse.'
        self.send_response(200)
        self.send_header('Content-Type', 'text/event-stream')
        self.end_headers()
        for change, finish in [(delta, None), ({}, 'tool_calls' if tools else 'stop')]:
            chunk = dict(id='fixture', object='chat.completion.chunk', model='local-fixture',
                         choices=[dict(index=0, delta=change, finish_reason=finish)])
            self.wfile.write(('data: ' + json.dumps(chunk) + '\n\n').encode())
        self.wfile.write(b'data: [DONE]\n\n')
    def log_message(self, *args):
        pass

HTTPServer(('127.0.0.1', 3893), Handler).serve_forever()
