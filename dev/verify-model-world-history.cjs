const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const scalar=x=>Array.isArray(x)&&x.length===1?x[0]:x;
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1400,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const ready=async()=>{await page.waitForTimeout(350);await page.waitForFunction(()=>!document.documentElement.classList.contains('shiny-busy'));};
 const save=async(name)=>{const event=page.waitForEvent('download');await page.locator('#world-save').click();await(await event).saveAs(name);return JSON.parse(fs.readFileSync(name,'utf8'));};
 try {
  await page.goto('http://127.0.0.1:3916');
  await page.locator('#world-consequences').getByText('Uncertain average outcome').waitFor({timeout:30000});
  await page.locator('#world-discuss_model').click();await ready();
  const composer=page.getByRole('textbox',{name:'Chat message',exact:true});
  assert.match(await composer.innerText(),/world implied/);
  await composer.fill('Use read_inquiry to inspect my retained external model. Explain its predictions at 70 degC, distinguishing expected strength from one future measurement. Keep the synthetic provenance and extrapolation limit clear. Do not draft an interpretation or invoke the built-in regression or design tools.');
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  await page.locator('#status').filter({hasText:'No record suggestion was created'}).waitFor({timeout:120000});
  console.log('PASS live model conversation completes without creating a human interpretation');
  fs.writeFileSync('artifacts/model-world-live-chat.txt',await page.locator('body').ariaSnapshot());
  await page.screenshot({path:'artifacts/model-world-live-chat.png'});
  const nativeId=new URL(page.url()).searchParams.get('shinychat_conversation_id');
  assert.ok(nativeId,'native conversation URL');
  fs.writeFileSync('artifacts/model-world-native-id.txt',nativeId);
  await page.locator('#open_world').click();await ready();
  const before=await save('artifacts/model-world-live-before-review.json');
  assert.equal(before.model_worlds.length,1);assert.equal(before.model_implications.length,0);
  const answer=before.conversation.filter(m=>scalar(m.role)==='assistant').map(m=>scalar(m.text)).join('\n');
  assert.match(answer,/synthetic/i);assert.match(answer,/extrapolat/i);assert.match(answer,/future|individual/i);
  await page.locator('#world-scenario').evaluate(el=>{el.value=36;el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));});await ready();
  await page.locator('#world-draft').click();await ready();
  await page.locator('#world-reason').fill('The fitted range is 20 to 40 degrees; I would qualify predictions outside it.');
  await page.locator('#world-challenge').fill('Collect new independent coating preparations at 50 and 60 degrees.');
  await page.locator('#world-author').fill('History reviewer');await ready();
  await page.locator('#world-reviewed').check();await page.locator('#world-retain').click();
  await page.locator('#world-status').filter({hasText:'Interpretation and exact model predictions retained'}).waitFor();
  await ready();await page.waitForTimeout(1000);
  const record=await save('artifacts/model-world-native-before.json');
  assert.equal(record.model_implications.length,1);
  await page.goto(`http://127.0.0.1:3916/?shinychat_conversation_id=${nativeId}`);
  await page.locator('#status').filter({hasText:'record restored'}).waitFor({timeout:60000});
  assert.equal(await page.locator('.modal.show').count(),0,'restore conversation before opening a model');
  await page.locator('#open_world').click();await ready();
  await page.locator('#world-reviews details summary').first().click();
  await page.locator('#world-reviews').filter({hasText:'History reviewer'}).waitFor();
  assert.equal(await page.locator('#world-scenario-value').innerText(),'70');
  assert.equal(await page.locator('#world-reviewed').isChecked(),false);
  const reopened=await save('artifacts/model-world-native-reopened.json');
  assert.deepEqual(reopened.model_worlds,record.model_worlds);
  assert.deepEqual(reopened.model_implications,record.model_implications);
  assert.deepEqual(reopened.revisions,record.revisions);
  assert.equal(reopened.conversation.length,record.conversation.length);
  assert.equal(await page.locator('.shiny-output-error:visible').count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS native URL restore preserves exact models, review, main claim and conversation; no acceptance replay');
 } catch(e) {fs.writeFileSync('artifacts/model-world-native-failure.txt',await page.locator('body').ariaSnapshot());await page.screenshot({path:'artifacts/model-world-native-failure.png'});throw e;}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
